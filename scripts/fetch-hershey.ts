// C12b: regenerate src/understand/hershey-data.ts from the public-domain Hershey font data (SPEC 17.5 item 2).
// The data is pinned to one commit of kamalmostafa/hershey-fonts (a converted copy of the original Usenet distribution) and
// each file's sha256 is checked before anything is written. The generated module is committed, so builds and tests need
// no network. Run only to re-pin:  tsx scripts/fetch-hershey.ts
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const COMMIT = '1356bf2f83d380fcef68c887e88675eb9d445d86';
const BASE = `https://raw.githubusercontent.com/kamalmostafa/hershey-fonts/${COMMIT}/hershey-fonts`;
/** face name used by the reader -> file, and the sha256 of that file at the pinned commit */
const FILES: { face: string; file: string; sha256: string }[] = [
  { face: 'simplex', file: 'rowmans.jhf', sha256: '8718fb129c0f6bce89c84fe41bc467e39534d215a6f7c3220cc5789a8a7d8618' },
  { face: 'duplex', file: 'rowmand.jhf', sha256: 'c56497b162a3831f0da2e189ada4a7335ce81b1c3c1cf380b2ced04287313d2e' },
  { face: 'complex', file: 'timesr.jhf', sha256: 'c454a5ed471aa33c1aac8c5b21c2d343e828805af2b48eebba20c46f492d9457' },
];
const NOTICE_SHA = '6ffb639e2d2799e987cec4f913473d4119e4270b65c13ceafe1cd502f904d855';

async function get(name: string): Promise<string> {
  const r = await fetch(`${BASE}/${name}`);
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  return r.text();
}
const sha = (s: string): string => crypto.createHash('sha256').update(s).digest('hex');

async function main(): Promise<void> {
  const notice = await get('hershey.txt');
  if (sha(notice) !== NOTICE_SHA) throw new Error('hershey.txt does not match the pinned sha256');
  const out: string[] = [
    '// GENERATED by scripts/fetch-hershey.ts. Do not edit.',
    '// The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the U. S. National Bureau of Standards.',
    '// The format of the font data in this distribution was originally created by James Hurt, Cognition, Inc.',
    '// Public domain under the Usenet distribution notice (use for any purpose provided these acknowledgements travel with the data).',
    `// Source: github.com/kamalmostafa/hershey-fonts commit ${COMMIT}, hershey-fonts/*.jhf (ASCII-ordered conversion).`,
    '// Pinned: each face below records the sha256 of the file it was built from.',
    `export const HERSHEY_SOURCE = { repo: 'kamalmostafa/hershey-fonts', commit: '${COMMIT}', notice: 'hershey.txt', noticeSha256: '${NOTICE_SHA}' } as const;`,
    'export const HERSHEY_FACES: Record<string, { file: string; sha256: string; lines: string[] }> = {',
  ];
  for (const f of FILES) {
    const text = await get(f.file);
    if (sha(text) !== f.sha256) throw new Error(`${f.file} does not match the pinned sha256`);
    const lines = text.split('\n').filter((l) => l.length > 0);
    out.push(`  ${f.face}: { file: '${f.file}', sha256: '${f.sha256}', lines: [`);
    for (const l of lines) out.push(`    ${JSON.stringify(l)},`);
    out.push('  ] },');
  }
  out.push('};', '');
  const dest = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/understand/hershey-data.ts');
  fs.writeFileSync(dest, out.join('\n'));
  console.log(`wrote ${dest}`);
}
void main();
